#!/usr/bin/env swift
// Writes every platform's colours from docs/design-system/tokens.json, so the skins can't drift apart.
//   swift scripts/tokens.swift           writes the files below
//   swift scripts/tokens.swift --check   changes nothing; fails if one of them is stale
// Mac: Resources/Assets.xcassets/<token>.colorset (Aluminium light, Lead dark: the Rams skin) and
//      Sources/DesignSystem/TokenPalettes.swift (ColorToken and the always-dark skins).
// Android TV: android/app/src/main/java/pt/nunomartins/nuva/ui/Palettes.kt (Palette and every theme).
// Windows: windows/NuVa.Core/TokenPalettes.cs (Token, Rams as light/dark pairs, the always-dark skins).
import Foundation

struct Tokens: Decodable {
    struct Theme: Decodable { let id: String; let name: String }
    struct Token: Decodable { let name: String; let value: [String: String]; let usage: String? }
    struct Colors: Decodable { let themes: [Theme]; let tokens: [Token] }
    let color: Colors
}

let check = CommandLine.arguments.contains("--check")
let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
guard let data = try? Data(contentsOf: root.appendingPathComponent("docs/design-system/tokens.json")),
      let tokens = try? JSONDecoder().decode(Tokens.self, from: data).color else {
    print("docs/design-system/tokens.json is missing or isn't valid"); exit(1)
}
var problems: [String] = []
let generated = "Generated by scripts/tokens.swift from docs/design-system/tokens.json: change the tokens and run it, never this file."

/// "display-ink" → "displayInk"; "Graphite Orange" → "graphiteOrange".
func camel(_ s: String) -> String {
    let parts = s.split(whereSeparator: { $0 == "-" || $0 == " " }).map(String.init)
    return parts[0].lowercased() + parts.dropFirst().map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
}
func hex(_ token: Tokens.Token, _ theme: String) -> String {
    guard let v = token.value[theme], v.count == 7, v.hasPrefix("#") else {
        problems.append("tokens.json: \(token.name) has no #RRGGBB for \(theme)"); return "000000"
    }
    return String(v.dropFirst()).uppercased()
}

// MARK: - Mac

let lead = "chumbo", aluminium = "aluminio"
func colorset(_ t: Tokens.Token) -> String {
    // The layout Xcode writes, so the files only change when a colour does.
    func color(_ h: String) -> String {
        let c = Array(h)
        return """
              "color": {
                "color-space": "srgb",
                "components": {
                  "alpha": "1.000",
                  "red": "0x\(String(c[0...1]))",
                  "green": "0x\(String(c[2...3]))",
                  "blue": "0x\(String(c[4...5]))"
                }
              }
        """
    }
    return """
    {
      "colors": [
        {
          "idiom": "universal",
    \(color(hex(t, aluminium)))
        },
        {
          "idiom": "universal",
          "appearances": [
            {
              "appearance": "luminosity",
              "value": "dark"
            }
          ],
    \(color(hex(t, lead)))
        }
      ],
      "info": {
        "author": "xcode",
        "version": 1
      }
    }

    """
}

let darkSkins = tokens.themes.filter { ![lead, aluminium].contains($0.id) }
let swift = """
// \(generated)

/// The design system's colour tokens. A skin gives each one a value; it never adds a role or moves the accent to another one.
enum ColorToken: String, CaseIterable, Sendable {
\(tokens.tokens.map { camel($0.name) == $0.name ? "    case \($0.name)" : "    case \(camel($0.name)) = \"\($0.name)\"" }.joined(separator: "\n"))
}

/// The always-dark skins' value for every token, as 0xRRGGBB. Rams uses the colour sets in Assets.xcassets.
enum TokenPalette {
\(darkSkins.map { theme in
    "    static let \(camel(theme.name)): [ColorToken: UInt32] = [\n"
        + tokens.tokens.map { "        .\(camel($0.name)): 0x\(hex($0, theme.id))," }.joined(separator: "\n")
        + "\n    ]"
}.joined(separator: "\n\n"))
}

"""

// MARK: - Android TV

let kotlin = """
// \(generated)
package pt.nunomartins.nuva.ui

import androidx.compose.ui.graphics.Color

/** A skin's value for every token of docs/design-system/tokens.json. Skins change colours only. */
data class Palette(
\(tokens.tokens.map { "    val \(camel($0.name)): Color," }.joined(separator: "\n"))
)

private fun rgb(hex: Long) = Color(0xFF000000 or hex)

/** Every theme in the tokens: Lead, Aluminium and the always-dark skins. */
object Palettes {
\(tokens.themes.map { theme in
    "    val \(camel(theme.name)) = Palette(\n"
        + tokens.tokens.map { "        \(camel($0.name)) = rgb(0x\(hex($0, theme.id)))," }.joined(separator: "\n")
        + "\n    )"
}.joined(separator: "\n\n"))
}

"""

// MARK: - Windows

/// "display-ink" → "DisplayInk", as C# names the tokens.
func pascal(_ s: String) -> String { let c = camel(s); return c.prefix(1).uppercased() + c.dropFirst() }
let csharp = """
// \(generated)
using System.Collections.Generic;

namespace NuVa.Core;

/// <summary>The design system's colour tokens. A skin gives each one a value; it never adds a role or moves the accent to another one.</summary>
public enum Token
{
\(tokens.tokens.map { "    \(pascal($0.name))," }.joined(separator: "\n"))
}

/// <summary>Every skin's value for every token, as 0xRRGGBB.</summary>
public static class TokenPalettes
{
    /// <summary>Rams: Aluminium (light) and Lead (dark), following Windows' app mode.</summary>
    public static readonly IReadOnlyDictionary<Token, (uint Light, uint Dark)> Rams = new Dictionary<Token, (uint, uint)>
    {
\(tokens.tokens.map { "        [Token.\(pascal($0.name))] = (0x\(hex($0, aluminium)), 0x\(hex($0, lead)))," }.joined(separator: "\n"))
    };
\(darkSkins.map { theme in
    "\n    public static readonly IReadOnlyDictionary<Token, uint> \(pascal(theme.name)) = new Dictionary<Token, uint>\n    {\n"
        + tokens.tokens.map { "        [Token.\(pascal($0.name))] = 0x\(hex($0, theme.id))," }.joined(separator: "\n")
        + "\n    };"
}.joined(separator: "\n"))
}

"""

// MARK: - Write or check

var outputs = tokens.tokens.map { ("Resources/Assets.xcassets/\($0.name).colorset/Contents.json", colorset($0)) }
outputs.append(("Sources/DesignSystem/TokenPalettes.swift", swift))
outputs.append(("android/app/src/main/java/pt/nunomartins/nuva/ui/Palettes.kt", kotlin))
if FileManager.default.fileExists(atPath: root.appendingPathComponent("windows/NuVa.Core").path) {
    outputs.append(("windows/NuVa.Core/TokenPalettes.cs", csharp))
}

for (path, text) in outputs {
    let url = root.appendingPathComponent(path)
    let current = try? String(contentsOf: url, encoding: .utf8)
    guard current != text else { continue }
    if check { problems.append("\(path) is stale: run swift scripts/tokens.swift"); continue }
    try! FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
    try! text.write(to: url, atomically: true, encoding: .utf8)
    print("wrote \(path)")
}
// A token that was removed leaves its colour set behind.
let assets = root.appendingPathComponent("Resources/Assets.xcassets")
for dir in (try? FileManager.default.contentsOfDirectory(atPath: assets.path)) ?? [] where dir.hasSuffix(".colorset") {
    if !tokens.tokens.contains(where: { $0.name + ".colorset" == dir }) { problems.append("Assets.xcassets/\(dir) has no token") }
}

if problems.isEmpty {
    print(check ? "Colours are in step with tokens.json." : "Done.")
} else {
    problems.forEach { print("✗ \($0)") }
    exit(1)
}
